using System.Text.Json;
using Microsoft.Extensions.Options;
using Taleweaver.Api.Common;
using Taleweaver.Api.Engine;

namespace Taleweaver.Api.Storage;

/// <summary>One file per game, &lt;id&gt;.json, written atomically. The file is also the export format.</summary>
public sealed class JsonGameStore(IOptions<ContentOptions> options) : IGameStore
{
    private readonly string _folder = string.IsNullOrWhiteSpace(options.Value.SavesPath)
        ? Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData), "Middara", "saves")
        : options.Value.SavesPath;

    public async Task<Game?> GetAsync(string id, CancellationToken cancellationToken)
    {
        var path = PathOf(id);
        if (path is null || !File.Exists(path))
        {
            return null;
        }

        await using var stream = File.OpenRead(path);
        return await JsonSerializer.DeserializeAsync<Game>(stream, JsonDefaults.Options, cancellationToken);
    }

    public async Task<IReadOnlyList<Game>> ListAsync(CancellationToken cancellationToken)
    {
        if (!Directory.Exists(_folder))
        {
            return [];
        }

        var games = new List<Game>();
        foreach (var path in Directory.EnumerateFiles(_folder, "*.json"))
        {
            if (await GetAsync(Path.GetFileNameWithoutExtension(path), cancellationToken) is { } game)
            {
                games.Add(game);
            }
        }

        return games.OrderByDescending(g => g.UpdatedAt).ToList();
    }

    public Task SaveAsync(Game game, CancellationToken cancellationToken) =>
        AtomicFile.WriteJsonAsync(PathOf(game.Id) ?? throw new ArgumentException($"Invalid game id '{game.Id}'."), game, cancellationToken);

    public Task<bool> DeleteAsync(string id, CancellationToken cancellationToken)
    {
        var path = PathOf(id);
        if (path is null || !File.Exists(path))
        {
            return Task.FromResult(false);
        }

        File.Delete(path);
        return Task.FromResult(true);
    }

    /// <summary>Ids are generated by the app (32 hex digits); anything else never reaches the disk.</summary>
    private string? PathOf(string id) =>
        id.Length is > 0 and <= 64 && id.All(char.IsAsciiLetterOrDigit) ? Path.Combine(_folder, $"{id}.json") : null;
}
